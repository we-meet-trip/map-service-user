-- V010__chat_invite_expiry.sql — 초대 링크에 방과 별개인 유효기간 추가
--
-- 책임: 초대 링크가 스스로 만료되게 한다. 이전에는 링크의 수명이 방의 수명과
--       같아서, 여행이 한참 뒤인 일정일수록 링크가 그만큼 오래 살아 있었다.
--       한 번 흘러나간 주소가 몇 주씩 열려 있는 셈이라, 받은 사람이 다시
--       퍼뜨리면 막을 방법이 발급자에게 없었다.
--
-- 스키마: user_service
--
-- 컬럼(nullable — 이 마이그레이션 이전에 발급된 링크는 값이 없다):
-- - invite_expires_at : 이 링크가 스스로 죽는 시각. 값이 없으면 독립 만료가
--                       없다는 뜻이고, 그때는 방 만료만으로 판정한다. 기존 행을
--                       채우지 않는 이유는 created_at 이 방을 만든 시각이지
--                       링크를 발급한 시각이 아니어서, 그것으로 채우면 있지도
--                       않았던 만료를 지어내게 되기 때문이다.
--
-- 인덱스를 두지 않는 이유: 링크 조회는 언제나 invite_token_hash 로 먼저 찾고,
-- 만료는 찾아낸 행 하나를 두고 따진다. 이 컬럼으로 훑는 조회가 없다.
--
-- 되돌리기: ALTER TABLE user_service.chat_rooms DROP COLUMN invite_expires_at;
-- =============================================================================

ALTER TABLE user_service.chat_rooms
    ADD COLUMN IF NOT EXISTS invite_expires_at TIMESTAMPTZ;
